-- PaparoniPac score reset and clean schema (destructive by design).
-- Run in Supabase SQL Editor. This deletes all old and current leaderboard/session rows.

drop table if exists public.pacman_score_sessions cascade;
drop table if exists public.pacman_scores cascade;
drop table if exists public.paparonipac_score_sessions cascade;
drop table if exists public.paparonipac_scores cascade;
drop table if exists public.paparoni_pac_score_sessions cascade;
drop table if exists public.paparoni_pac_scores cascade;

create table public.paparoni_pac_scores (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 10),
  score integer not null check (score >= 0),
  created_at timestamptz not null default now()
);

create index paparoni_pac_scores_rank_idx
  on public.paparoni_pac_scores (score desc, created_at asc);

alter table public.paparoni_pac_scores enable row level security;
grant select on public.paparoni_pac_scores to anon, authenticated;
grant all on public.paparoni_pac_scores to service_role;
create policy "PaparoniPac scores are publicly readable"
  on public.paparoni_pac_scores for select
  to anon, authenticated using (true);

create table public.paparoni_pac_score_sessions (
  nonce uuid primary key,
  started_at timestamptz not null,
  submitted_at timestamptz
);

alter table public.paparoni_pac_score_sessions enable row level security;
grant all on public.paparoni_pac_score_sessions to service_role;
